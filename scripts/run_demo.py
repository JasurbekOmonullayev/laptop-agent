"""Run the task's sample questions through the agent and write the conversations to docs/demo_log.md.

Uses the real database and the real LLM (a few cents). Every answer, tool call and booking status change in the
log is what the agent really did in this run; nothing is edited by hand.

Run: python scripts/run_demo.py
"""
import json
import sys
import time
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

PROJECT_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_DIR))

from app.agent import handle_message, new_conversation  # noqa: E402
from app.config import settings  # noqa: E402
from app.db import connect  # noqa: E402

LOG_PATH = PROJECT_DIR / "docs" / "demo_log.md"
TASHKENT = ZoneInfo("Asia/Tashkent")

# Each scenario is one conversation. The numbers are the task's sample questions.
SCENARIOS = [
    ("Products and stock", [
        "SO29592578 qanday protsessor, RAM va kafolatga ega, narxi qancha?",                       # 1 (uz)
        "I need a 16-inch laptop with 16 GB RAM for under 7 million soums. What do you have?",   # 2 (en)
        "У вас есть MacBook Air 15 M5 (SO29229993)?",                                             # 3 (ru)
        "Compare SO29466784 and SO29465551. Which is better for programming?",                    # 4 (en)
        "Talabaman, byudjetim 8 mln so'm, asosan Word va Zoom uchun. Nima tavsiya qilasiz?",      # 5 (uz)
    ]),
    ("Working procedures", [
        "What are your working hours?",                                                           # 6 (en)
        "Как долго вы держите бронь?",                                                            # 7 (ru)
        "Ikkita olsam 10% chegirma bera olasizmi?",                                               # 8 (uz)
    ]),
    ("Booking: confirm, limit, declined summary, status, cancel", [
        "Book 2 units of SO29466784 for Aziz Karimov, +998901234567.",                            # 9
        "yes",
        "Book 5 units of SO29321618.",                                                            # 10
        "OK, then 1 unit of SO29321618, same name and phone.",
        "no",                                                                                     # declined summary
        "What is the status of my booking?",                                                      # 11
        "Cancel my booking.",                                                                     # 12
        "yes",
    ]),
    ("Trade agreements (answers only from the PDF)", [
        "I bought a laptop but don't like it. Can I return it, and within how many days?",        # 13 (en)
        "Under what conditions can a laptop of proper quality be returned?",                      # 14 (en)
        "Noutbukimda nuqson chiqdi. Nimani talab qila olaman?",                                   # 15 (uz)
        "Сколько дней мой заказ будет ждать в пункте выдачи?",                                    # 16 (ru)
        "I refused the whole order because it was defective. Will the delivery cost be refunded?",  # 17 (en)
        "What is your company's tax ID?",                                                         # 18 (en, trap)
    ]),
    ("Off-topic", [
        "Who will win the next US presidential election?",
    ]),
]


def tool_calls_since(conversation_id: str, after_id: int) -> list[str]:
    with connect() as conn:
        rows = conn.execute(
            "SELECT content FROM messages WHERE conversation_id = %s AND role = 'tool' AND id > %s ORDER BY id",
            [conversation_id, after_id],
        ).fetchall()
    calls = []
    for row in rows:
        entry = json.loads(row["content"])
        arguments = entry.get("arguments") or ""
        calls.append(f"`{entry['tool']}({arguments})`" if arguments else f"`{entry['tool']}`")
    return calls


def last_message_id() -> int:
    with connect() as conn:
        return conn.execute("SELECT coalesce(max(id), 0) AS id FROM messages").fetchone()["id"]


def status_log(conversation_ids: list[str]) -> list[dict]:
    with connect() as conn:
        return conn.execute(
            """SELECT l.changed_at, l.booking_id, b.offer_no, b.quantity, l.old_status, l.new_status, l.actor
               FROM booking_status_log l JOIN bookings b USING (booking_id)
               WHERE b.conversation_id = ANY(%s::uuid[]) ORDER BY l.id""",
            [conversation_ids],
        ).fetchall()


def main() -> None:
    lines = [
        "# Demo log",
        "",
        f"Run on {datetime.now():%Y-%m-%d %H:%M} with `{settings.llm_model}`. Generated by `scripts/run_demo.py`;",
        "every answer, tool call and status change below is what the agent really did.",
        "",
    ]
    conversation_ids = []
    for title, messages in SCENARIOS:
        conversation_id = new_conversation()
        conversation_ids.append(conversation_id)
        lines += [f"## {title}", "", f"Conversation `{conversation_id}`", ""]
        for text in messages:
            print(f"> {text}")
            before = last_message_id()
            started = time.time()
            answer = handle_message(conversation_id, text)
            seconds = time.time() - started
            tools = tool_calls_since(conversation_id, before)
            lines += [f"**Client:** {text}", ""]
            lines += [f"*Tools: {', '.join(tools) if tools else 'none'} · {seconds:.1f} s*", ""]
            lines += ["**Agent:**", "", answer, "", "---", ""]

    lines += ["## Booking status log (from `booking_status_log`)", "",
              "| Time (Tashkent) | Booking | Laptop | Qty | Old status | New status | Actor |", "|---|---|---|---|---|---|---|"]
    for row in status_log(conversation_ids):
        lines.append(f"| {row['changed_at'].astimezone(TASHKENT):%H:%M:%S} | {row['booking_id']} | {row['offer_no']} | {row['quantity']} "
                     f"| {row['old_status'] or '-'} | {row['new_status']} | {row['actor']} |")

    LOG_PATH.parent.mkdir(exist_ok=True)
    LOG_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"written: {LOG_PATH}")


if __name__ == "__main__":
    main()
    